def __getattr__(name: str) -> object:
    # The stream needs the optional websockets dependency; import it lazily.
    if name in ("CabalSpyIDStream", "STREAM_EVENTS", "THESIS_EVENTS"):
        from . import _stream

        return getattr(_stream, name)
    if name in ("ThesesStream", "THESES_STREAM_EVENTS"):
        from . import _theses_stream

        return getattr(_theses_stream, name)
    if name in ("CalloutsStream", "CALLOUTS_STREAM_EVENTS", "CALLOUT_EVENTS"):
        from . import _callouts_stream

        return getattr(_callouts_stream, name)
    if name in ("CopyTradingStream", "COPY_TRADING_STREAM_EVENTS", "COPY_TRADING_EVENTS"):
        from . import _copy_trading_stream

        return getattr(_copy_trading_stream, name)
    if name in ("TradeFeedStream", "TRADE_FEED_STREAM_EVENTS", "TRADE_FEED_EVENTS"):
        from . import _trade_feed_stream

        return getattr(_trade_feed_stream, name)
    raise AttributeError(f"module 'cabalspy_id' has no attribute {name!r}")


